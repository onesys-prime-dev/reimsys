import { chromium } from 'playwright';
const b = await chromium.launch({ channel: 'chrome' });
const p = await b.newPage({ baseURL: 'http://localhost:5173' });
p.on('console', m => console.log('console', m.type(), m.text()));
p.on('pageerror', e => console.log('pageerror', String(e)));
p.on('response', r => r.url().includes('/api') && console.log(r.status(), r.url()));
await p.goto('/'); await p.waitForTimeout(1500);
await p.fill('input[type=email]', 'admin@example.com'); await p.fill('input[type=password]', 'Reimsis#2026');
await p.click('button[type=submit]'); await p.waitForTimeout(2000);
console.log((await p.locator('body').innerText()).slice(0, 300));
await b.close();
