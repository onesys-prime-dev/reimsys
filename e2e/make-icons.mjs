// Draws the logo into the PNG icons used when someone adds REIMSYS to a phone's home screen.
// Run again if the logo in packages/shared/src/brand.ts changes:  node e2e/make-icons.mjs
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';

const pub = path.resolve('apps/web/public');
const svg = fs.readFileSync(path.join(pub, 'favicon.svg'), 'utf8');
// Phone icon masks round the corners themselves, so those icons are full-bleed squares.
// (the folded tile is swapped for a plain square, and the fold dropped)
const full = svg
  .replace(/<path id="tile"[^>]*\/>/, '<rect width="64" height="64" fill="url(#g)"/>')
  .replace(/<path id="fold"[^>]*\/>/, '');
if (full === svg || full.includes('id="fold"')) throw new Error('favicon.svg no longer has the tile and fold the icon script expects');

const b = await chromium.launch({ channel: 'chrome' });
for (const [file, size, markup] of [
  ['apple-touch-icon.png', 180, full],
  ['icon-192.png', 192, full],
  ['icon-512.png', 512, full],
  ['favicon-32.png', 32, svg],
  ['email-logo.png', 68, svg],
]) {
  const p = await b.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
  await p.setContent(`<html><body style="margin:0;background:transparent">${markup.replace('<svg ', `<svg width="${size}" height="${size}" `)}</body></html>`);
  if (file === 'email-logo.png') {
    const png = await p.screenshot({ omitBackground: true });
    fs.writeFileSync(path.resolve('apps/api/src/lib/emailLogo.ts'), `// Generated by e2e/make-icons.mjs from the logo. Do not edit by hand.\nexport const EMAIL_LOGO_PNG_BASE64 = '${png.toString('base64')}';\n`);
    await p.close();
    console.log('wrote apps/api/src/lib/emailLogo.ts');
    continue;
  }
  await p.screenshot({ path: path.join(pub, file), omitBackground: true });
  await p.close();
  console.log('wrote', file);
}
await b.close();

fs.writeFileSync(path.join(pub, 'manifest.webmanifest'), JSON.stringify({
  name: 'REIMSYS',
  short_name: 'REIMSYS',
  description: 'Reimbursement management',
  start_url: '/',
  display: 'standalone',
  background_color: '#f9fbfb',
  theme_color: '#0c7480',
  icons: [
    { src: '/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any maskable' },
    { src: '/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any maskable' },
    { src: '/favicon.svg', sizes: 'any', type: 'image/svg+xml' },
  ],
}, null, 2) + '\n');
console.log('wrote manifest.webmanifest');
